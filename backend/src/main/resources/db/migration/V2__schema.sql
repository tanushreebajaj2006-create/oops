-- ==============================================================================
-- Flyway V2: ServiceDesk schema
--
-- Portable SQL: runs unchanged on PostgreSQL 16 (dev/prod) and on H2 in
-- PostgreSQL mode (automated tests), so the tests exercise the real migrations.
--
-- Conventions
--   * Enum-like columns are VARCHAR + CHECK constraints (readable, portable).
--   * All timestamps are TIMESTAMP WITH TIME ZONE and hold UTC instants.
--   * Users, incidents and services use natural, human-readable keys
--     (E102, INC1024, PAYMENT) because people type and read them.
--   * Technician workload is NOT stored: it is counted from open incidents
--     on load, so it can never drift out of sync.
-- ==============================================================================

CREATE SEQUENCE incident_seq START WITH 1001 INCREMENT BY 1;
CREATE SEQUENCE user_seq START WITH 500 INCREMENT BY 1;

-- ------------------------------------------------------------------------------
-- Reference data
-- ------------------------------------------------------------------------------
CREATE TABLE categories (
    code    VARCHAR(30) PRIMARY KEY,
    name    VARCHAR(60) NOT NULL,
    active  BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE it_services (
    code        VARCHAR(40) PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    criticality VARCHAR(10) NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_services_criticality CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

-- ------------------------------------------------------------------------------
-- Users (single table for the User class hierarchy; role says which subclass)
-- ------------------------------------------------------------------------------
CREATE TABLE users (
    id               VARCHAR(20)  PRIMARY KEY,
    user_role        VARCHAR(20)  NOT NULL,
    full_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(254) NOT NULL,
    password_hash    VARCHAR(100),
    phone            VARCHAR(20),
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    -- employee only
    department       VARCHAR(80),
    -- technician / team lead only
    experience_years INTEGER,
    max_workload     INTEGER,
    available        BOOLEAN,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (user_role IN ('EMPLOYEE', 'TECHNICIAN', 'TEAM_LEAD', 'ADMINISTRATOR')),
    CONSTRAINT ck_users_workload CHECK (max_workload IS NULL OR max_workload BETWEEN 1 AND 50)
);

CREATE TABLE user_skills (
    user_id       VARCHAR(20) NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_code VARCHAR(30) NOT NULL REFERENCES categories (code),
    proficiency   INTEGER     NOT NULL,
    PRIMARY KEY (user_id, category_code),
    CONSTRAINT ck_skills_proficiency CHECK (proficiency BETWEEN 1 AND 5)
);

-- ------------------------------------------------------------------------------
-- SLA policies: one default (service_code NULL) plus optional per-service ones
-- ------------------------------------------------------------------------------
CREATE TABLE sla_policies (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(80)      NOT NULL,
    service_code      VARCHAR(40)      REFERENCES it_services (code) ON DELETE CASCADE,
    warning_threshold DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_sla_policies_service UNIQUE (service_code),
    CONSTRAINT ck_sla_policies_threshold CHECK (warning_threshold BETWEEN 0.5 AND 0.95)
);

CREATE TABLE sla_targets (
    policy_id          BIGINT     NOT NULL REFERENCES sla_policies (id) ON DELETE CASCADE,
    priority           VARCHAR(2) NOT NULL,
    response_seconds   BIGINT     NOT NULL,
    resolution_seconds BIGINT     NOT NULL,
    PRIMARY KEY (policy_id, priority),
    CONSTRAINT ck_sla_targets_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_sla_targets_order CHECK (response_seconds > 0 AND resolution_seconds >= response_seconds)
);

-- ------------------------------------------------------------------------------
-- Incidents (aggregate root) and their notes (composition)
-- ------------------------------------------------------------------------------
CREATE TABLE incidents (
    id                    VARCHAR(20)   PRIMARY KEY,
    reporter_id           VARCHAR(20)   NOT NULL REFERENCES users (id),
    title                 VARCHAR(120)  NOT NULL,
    description           VARCHAR(4000) NOT NULL,
    service_code          VARCHAR(40)   NOT NULL REFERENCES it_services (code),
    impact                VARCHAR(10)   NOT NULL,
    urgency               VARCHAR(10)   NOT NULL,
    affected_users        INTEGER       NOT NULL,
    category_code         VARCHAR(30)   REFERENCES categories (code),
    priority              VARCHAR(2),
    status                VARCHAR(20)   NOT NULL,
    assignee_id           VARCHAR(20)   REFERENCES users (id),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_at       TIMESTAMP WITH TIME ZONE,
    resolved_at           TIMESTAMP WITH TIME ZONE,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    reopen_count          INTEGER       NOT NULL DEFAULT 0,
    -- resolution (owned value)
    resolution_summary    VARCHAR(2000),
    resolution_root_cause VARCHAR(2000),
    resolved_by           VARCHAR(20)   REFERENCES users (id),
    -- feedback (owned value)
    feedback_rating       INTEGER,
    feedback_comment      VARCHAR(1000),
    feedback_at           TIMESTAMP WITH TIME ZONE,
    -- closure (owned value); closed_by may be the SYSTEM actor, so no foreign key
    closed_by             VARCHAR(20),
    closed_at             TIMESTAMP WITH TIME ZONE,
    closure_note          VARCHAR(2000),
    -- optimistic locking: two people saving the same incident cannot overwrite each other
    version               BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_incidents_impact CHECK (impact IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incidents_urgency CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incidents_priority CHECK (priority IS NULL OR priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_incidents_status CHECK (status IN ('NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED',
        'IN_PROGRESS', 'AWAITING_INFO', 'RESOLVED', 'VERIFIED', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_incidents_users CHECK (affected_users >= 1),
    CONSTRAINT ck_incidents_rating CHECK (feedback_rating IS NULL OR feedback_rating BETWEEN 1 AND 5)
);

CREATE INDEX ix_incidents_status   ON incidents (status);
CREATE INDEX ix_incidents_assignee ON incidents (assignee_id, status);
CREATE INDEX ix_incidents_reporter ON incidents (reporter_id);
CREATE INDEX ix_incidents_service  ON incidents (service_code);
CREATE INDEX ix_incidents_created  ON incidents (created_at);

CREATE TABLE incident_notes (
    incident_id VARCHAR(20)   NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    note_order  INTEGER       NOT NULL,
    author_id   VARCHAR(20)   NOT NULL REFERENCES users (id),
    note_type   VARCHAR(20)   NOT NULL,
    body        VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (incident_id, note_order),
    CONSTRAINT ck_notes_type CHECK (note_type IN ('INVESTIGATION', 'INFO_REQUEST', 'INFO_RESPONSE', 'COMMENT'))
);

-- ------------------------------------------------------------------------------
-- Audit trail: append-only. No foreign keys on purpose - history must survive
-- even if referenced rows are archived, and the SYSTEM actor is not a user row.
-- ------------------------------------------------------------------------------
CREATE TABLE audit_log (
    seq             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id        VARCHAR(20)   NOT NULL,
    actor_role      VARCHAR(20)   NOT NULL,
    action          VARCHAR(40)   NOT NULL,
    incident_id     VARCHAR(20),
    previous_status VARCHAR(20),
    new_status      VARCHAR(20),
    description     VARCHAR(4000) NOT NULL
);

CREATE INDEX ix_audit_incident ON audit_log (incident_id, seq);
CREATE INDEX ix_audit_actor    ON audit_log (actor_id);
CREATE INDEX ix_audit_time     ON audit_log (occurred_at);

-- ------------------------------------------------------------------------------
-- In-app notifications (the bell) and recorded SLA alerts
-- ------------------------------------------------------------------------------
CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id VARCHAR(20)   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel      VARCHAR(20)   NOT NULL,
    subject      VARCHAR(300)  NOT NULL,
    body         VARCHAR(4000) NOT NULL,
    incident_id  VARCHAR(20)   NOT NULL,
    event_type   VARCHAR(30)   NOT NULL,
    urgent       BOOLEAN       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read      BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX ix_notifications_recipient ON notifications (recipient_id, id);

CREATE TABLE sla_alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type  VARCHAR(10) NOT NULL,
    incident_id VARCHAR(20) NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    sla_kind    VARCHAR(12) NOT NULL,
    priority    VARCHAR(2)  NOT NULL,
    due_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    detected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assignee_id VARCHAR(20),
    CONSTRAINT uq_sla_alerts UNIQUE (incident_id, sla_kind, alert_type),
    CONSTRAINT ck_sla_alerts_type CHECK (alert_type IN ('WARNING', 'VIOLATION')),
    CONSTRAINT ck_sla_alerts_kind CHECK (sla_kind IN ('RESPONSE', 'RESOLUTION'))
);

CREATE INDEX ix_sla_alerts_type ON sla_alerts (alert_type, detected_at);
